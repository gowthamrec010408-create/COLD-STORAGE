/**
 * Solar Smart Cold Storage — Report Generation & Multi-Format Export Engine
 * Generates PDF (jsPDF + AutoTable), Excel (SheetJS), and CSV reports for:
 * - Daily / Weekly / Monthly Operational Logs
 * - Produce Quality & Spoilage Predictions
 * - Solar Energy & Battery Performance
 * - Sensor Calibration & System Audit
 */

import { store } from '../core/state.js';
import { SmartSellingEngine } from '../engine/smart-selling.js';

export class ReportGenerator {
  /**
   * Export to PDF format
   */
  static async exportPDF(reportType = 'daily') {
    const { jsPDF } = window.jspdf || {};
    if (!jsPDF) {
      alert('jsPDF library loading... Please try again in a moment.');
      return;
    }

    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    const now = new Date();
    const dateStr = now.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
    const timeStr = now.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });

    // 1. Header & Branding Banner
    doc.setFillColor(16, 185, 129); // Emerald Brand Color
    doc.rect(0, 0, 210, 24, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFontSize(16);
    doc.setFont('helvetica', 'bold');
    doc.text('SOLAR SMART COLD STORAGE', 14, 11);

    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.text('IoT Telemetry + AI Spoilage Prediction System | Post-Harvest Audit', 14, 18);

    doc.setFontSize(8);
    doc.text(`Generated: ${dateStr} ${timeStr}`, 145, 18);

    // 2. Report Title & Metadata
    doc.setTextColor(30, 41, 59);
    doc.setFontSize(13);
    doc.setFont('helvetica', 'bold');
    const title = reportType === 'daily' ? 'DAILY OPERATIONAL & SENSOR AUDIT REPORT' :
                  reportType === 'weekly' ? 'WEEKLY QUALITY & STORAGE SUMMARY' :
                  reportType === 'quality' ? 'AI PRODUCE FRESHNESS & SPOILAGE RISK ASSESSMENT' :
                  reportType === 'energy' ? 'SOLAR POWER & BATTERY EFFICIENCY REPORT' :
                  'THREE-ZONE COMPREHENSIVE STATUS REPORT';
    doc.text(title, 14, 34);

    const user = store.get('user') || { displayName: 'System Operator', organization: 'Precision Agro Storage' };
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 116, 139);
    doc.text(`Facility: ${user.organization} | Generated By: ${user.displayName} | Unit ID: ESP32-COLD-MASTER-01`, 14, 40);

    // 3. Three-Zone Current Status Table
    const zones = [1, 2, 3].map(id => store.get(`zones.${id}`));
    const zoneRows = zones.map(z => [
      `Zone ${z.id} (${z.crop})`,
      `${z.temperature.toFixed(1)} °C`,
      `${z.targetTempMin} - ${z.targetTempMax} °C`,
      `${z.humidity.toFixed(1)} %RH`,
      `${z.currentWeight.toFixed(1)} kg (-${z.weightLossPercent}%)`,
      `${z.ethylene.toFixed(2)} ppm`,
      z.tempStatus
    ]);

    if (doc.autoTable) {
      doc.autoTable({
        startY: 46,
        head: [['Storage Zone', 'Temp', 'Target Corridor', 'Humidity', 'Current Weight', 'Ethylene', 'Thermal Status']],
        body: zoneRows,
        theme: 'striped',
        headStyles: { fillColor: [15, 23, 42], textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
        styles: { fontSize: 8, cellPadding: 2.5 },
        alternateRowStyles: { fillColor: [248, 250, 252] }
      });
    }

    // 4. AI Spoilage & Batch Freshness Table
    let currentY = doc.lastAutoTable ? doc.lastAutoTable.finalY + 8 : 90;
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(30, 41, 59);
    doc.text('Produce Batches & AI Spoilage Prediction', 14, currentY);

    const batches = store.get('batches') || [];
    const zoneTelemetry = { 1: store.get('zones.1'), 2: store.get('zones.2'), 3: store.get('zones.3') };
    const rankedBatches = SmartSellingEngine.rankBatches(batches, zoneTelemetry);

    const batchRows = rankedBatches.map(b => [
      b.id,
      `${b.name} (${b.variety})`,
      `Zone ${b.zoneId}`,
      `${b.currentWeight} kg`,
      `${b.durationDays} days`,
      `${b.prediction.freshnessScore}%`,
      b.prediction.spoilageRisk,
      b.prediction.remainingShelfLifeText,
      b.marketActionText
    ]);

    if (doc.autoTable) {
      doc.autoTable({
        startY: currentY + 3,
        head: [['Batch ID', 'Produce', 'Zone', 'Weight', 'Age', 'Freshness', 'Risk', 'Shelf Life', 'Sell Action']],
        body: batchRows,
        theme: 'striped',
        headStyles: { fillColor: [16, 185, 129], textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
        styles: { fontSize: 8, cellPadding: 2.5 },
        alternateRowStyles: { fillColor: [248, 250, 252] }
      });
    }

    // 5. Solar & Energy Summary
    currentY = doc.lastAutoTable ? doc.lastAutoTable.finalY + 8 : 170;
    const energy = store.get('energy');
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(30, 41, 59);
    doc.text('Solar Generation & Energy Storage Performance', 14, currentY);

    const energyRows = [
      ['Solar PV Generation', `${energy.solarPowerW} W`, 'Battery State of Charge', `${energy.batteryPercent}% (${energy.batteryVoltageV} V)`],
      ['Cooling Load Demand', `${energy.coolingPowerW} W`, 'Operating Power Mode', energy.energyMode.replace('_', ' ')],
      ['Compressor Health', energy.compressorStatus, 'Daily Solar Harvest', `${energy.solarDailyKWh} kWh`]
    ];

    if (doc.autoTable) {
      doc.autoTable({
        startY: currentY + 3,
        head: [['Solar Metric', 'Value', 'Storage & Load Metric', 'Value']],
        body: energyRows,
        theme: 'grid',
        headStyles: { fillColor: [6, 182, 212], textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
        styles: { fontSize: 8, cellPadding: 2.5 }
      });
    }

    // 6. Scientific Disclaimer Footer
    const footerY = 285;
    doc.setFontSize(7);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(148, 163, 184);
    doc.text('Disclaimer: AI predictions are decision-support estimates based on IoT sensor data and biological degradation models.', 14, footerY);

    // Save and Trigger Download
    doc.save(`SolarSmart_Report_${reportType}_${now.toISOString().split('T')[0]}.pdf`);
  }

  /**
   * Export to Excel (XLSX) format via SheetJS
   */
  static exportExcel(reportType = 'all') {
    const XLSX = window.XLSX;
    if (!XLSX) {
      alert('Excel export library loading... Please try again in a moment.');
      return;
    }

    const wb = XLSX.utils.book_new();

    // Sheet 1: Zones Telemetry
    const zones = [1, 2, 3].map(id => {
      const z = store.get(`zones.${id}`);
      return {
        'Zone ID': z.id,
        'Zone Name': z.name,
        'Current Crop': z.crop,
        'Temperature (°C)': z.temperature,
        'Target Min (°C)': z.targetTempMin,
        'Target Max (°C)': z.targetTempMax,
        'Humidity (%RH)': z.humidity,
        'Initial Weight (kg)': z.initialWeight,
        'Current Weight (kg)': z.currentWeight,
        'Weight Loss (kg)': z.weightLoss,
        'Weight Loss (%)': z.weightLossPercent,
        'Ethylene (ppm)': z.ethylene,
        'Ethylene Trend (%)': z.ethyleneTrend,
        'Temp Status': z.tempStatus,
        'Last Update': z.lastUpdated
      };
    });
    const wsZones = XLSX.utils.json_to_sheet(zones);
    XLSX.utils.book_append_sheet(wb, wsZones, 'Zone Telemetry');

    // Sheet 2: Produce Batches & AI Prediction
    const batches = store.get('batches') || [];
    const zoneTelemetry = { 1: store.get('zones.1'), 2: store.get('zones.2'), 3: store.get('zones.3') };
    const ranked = SmartSellingEngine.rankBatches(batches, zoneTelemetry);

    const batchData = ranked.map(b => ({
      'Batch ID': b.id,
      'Produce': b.name,
      'Variety': b.variety,
      'Zone': b.zoneId,
      'Farmer': b.farmer,
      'Date Stored': b.dateStored,
      'Storage Days': b.durationDays,
      'Initial Weight (kg)': b.initialWeight,
      'Current Weight (kg)': b.currentWeight,
      'Freshness Score (%)': b.prediction.freshnessScore,
      'Spoilage Risk': b.prediction.spoilageRisk,
      'Remaining Shelf Life': b.prediction.remainingShelfLifeText,
      'Quality Trend': b.prediction.qualityTrend,
      'Recommended Action': b.marketActionText,
      'Urgency Score': b.urgencyScore
    }));
    const wsBatches = XLSX.utils.json_to_sheet(batchData);
    XLSX.utils.book_append_sheet(wb, wsBatches, 'Produce Batches');

    // Sheet 3: Energy & Solar
    const energy = store.get('energy');
    const energyData = [{
      'Solar Power (W)': energy.solarPowerW,
      'Solar Daily Total (kWh)': energy.solarDailyKWh,
      'Battery Level (%)': energy.batteryPercent,
      'Battery Voltage (V)': energy.batteryVoltageV,
      'Cooling Load (W)': energy.coolingPowerW,
      'Compressor Status': energy.compressorStatus,
      'Energy Mode': energy.energyMode
    }];
    const wsEnergy = XLSX.utils.json_to_sheet(energyData);
    XLSX.utils.book_append_sheet(wb, wsEnergy, 'Solar & Energy');

    // Write file
    XLSX.writeFile(wb, `SolarSmart_ColdStorage_Data_${new Date().toISOString().split('T')[0]}.xlsx`);
  }

  /**
   * Export to raw CSV
   */
  static exportCSV() {
    const XLSX = window.XLSX;
    if (!XLSX) {
      alert('CSV library loading... Please try again in a moment.');
      return;
    }
    const batches = store.get('batches') || [];
    const zoneTelemetry = { 1: store.get('zones.1'), 2: store.get('zones.2'), 3: store.get('zones.3') };
    const ranked = SmartSellingEngine.rankBatches(batches, zoneTelemetry);

    const batchData = ranked.map(b => ({
      'Batch ID': b.id,
      'Produce': b.name,
      'Variety': b.variety,
      'Zone': b.zoneId,
      'Current Weight (kg)': b.currentWeight,
      'Freshness (%)': b.prediction.freshnessScore,
      'Spoilage Risk': b.prediction.spoilageRisk,
      'Remaining Shelf Life': b.prediction.remainingShelfLifeText,
      'Action': b.marketActionText
    }));

    const ws = XLSX.utils.json_to_sheet(batchData);
    const csv = XLSX.utils.sheet_to_csv(ws);
    const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement('a');
    link.href = URL.createObjectURL(blob);
    link.setAttribute('download', `SolarSmart_Produce_Inventory_${new Date().toISOString().split('T')[0]}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  }
}
